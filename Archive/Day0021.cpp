// Day0021,引用语法及const引用
#include <iostream>
#include <string>
#include <vector>

using namespace std;

// 引用传递修改主函数实参
// 函数被调用是形参会对实参进行引用，此处int& num_1实际是对实参num_1起了一个一样的别名，若取num_3也是同样效果
void DoubleNum(int& num_1)
{
	num_1 *= 2;
}

// const引用函数
void PrintNum(const int& num_2)
{
	cout << "函数内利用const引用只读访问实参num2内容:" << num_2 << '\n';
}

// const引用函数
void ConstPrint(const int& num_3)
{
	cout << "使用const引用访问num_3:" << num_3 << '\n';
}
// 非const引用函数
void UnconstPrint(int& num_3)
{
	cout << "存在const引用后使用非const引用访问num_3:" << num_3 << '\n';
}

int& ReturnNum()
{
	// 静态变量，存放在全局区，函数调用结束后其地址指向的内存不会被编译器自动释放
	static int num_4{ 99 };
	return num_4;
}

int main()
{
	// ========== 引用语法及注意事项】 ==========
	{
		cout << "引用测试:" << '\n';

		// 创建的变量会存储在内存中，可以通过变量名、地址的方式访问、修改该内存
		// 变量即是在已有变量名的情况下为该内存起别名，同样可以通过这个别名来访问、修改内存
		// 语法:变量数据类型 &别名{变量原名称}
		int a{ 10 };
		int& b{ a };
		cout << "对变量a(10)进行引用b后访问b的内容:" << b << '\n';
		// 很显然别名b和变量名a之间的状态是同步的
		b = { 20 };
		cout << "修改b值为20后访问a的内容:" << a << '\n';
		// 引用注意事项：
		// 引用在初始化时不能零初始化，它必须绑定一个真实存在的对象
		// 引用进行初始化时与某段内存绑定后不能进行绑定对象的更改，例如：
		// 引用只要求需要有绑定对象，但不检查绑定对象是否还有效
		int* p = nullptr;
		int& r{ *p };
		// 此时执行cout访问则会运行后崩溃而非运行前报错
		// cout << r;

		cout << "测试结束" << '\n' << '\n';
	}

	// ========== 引用做形参修改实参 ==========
	{
		cout << "引用传递修改实参测试:" << '\n';

		// 引用底层实现原理是地址，用不可修改指向对象的指针实现，故引用必须绑定对象，且不能解绑
		// 且引用自带*解引用功能，对别名无需解引用就能进行访问、修改
		// 它在抗风险上与指针相比更优
		int num_1{ 30 };
		cout << "num_1原值为:" << num_1 << '\n';
		DoubleNum(num_1);
		cout << "将实参num_1传入函数中引用并修改为原来两倍:" << num_1 << '\n';

		cout << "测试结束" << '\n' << '\n';
	}

	// ========== const引用 ==========
	{
		cout << "const引用测试:" << '\n';

		// 引用经常和const搭配使用，可实现函数内只读访问传入实参内容的效果
		// 函数内形参通过引用获得实参地址，const用于禁止发生修改该形参的行为
		// 且通过地址访问就可避免值传递拷贝，适用于struct这类存储了大量内容的容器
		int num_2{ 39 };
		cout << "num_2原值:" << num_2 << '\n';
		PrintNum(num_2);
		// 在函数中用const修饰形参后也不影响主函数中访问、修改实参
		num_2 = 49;
		cout << "函数中用const修饰形参后在主函数中修改num_2值为49后num_2值为:" << num_2 << '\n';

		// 且const和非const两引用绑定同一对象能共存
		int num_3{ 345 };
		ConstPrint(num_3);
		UnconstPrint(num_3);

		cout << "测试结束" << '\n' << '\n';
	}

	// ========== 函数返回作为左值 ==========
	{
		cout << "函数返回作为左值测试:" << '\n';

		// 和学习new时同理，返回局部变量地址这个行为的风险在于此局部变量地址指向的内存是由编译器管理
		// 返回了存储在栈区的变量地址(仅警告)，函数调用结束后地址指向的内存被回收，访问该地址是访问生命周期已结束的对象，则会出错
		// 返回了存储在堆区、全局区的变量地址，此类地址指向的内存在函数调用结束后不回收，访问则不会出错
		// 由上可引出，若函数返回了堆区、全局区的变量的引用，此引用作为函数返回可以作为左值进行再赋值等操作
		cout << "静态变量num_4的值为:" << ReturnNum() << '\n';
		ReturnNum() = 1000;
		cout << "将静态变量num_4进行引用并返回后作为左值赋值为1000后num_4为:" << ReturnNum() << '\n';

		cout << "测试结束" << '\n' << '\n';
	}
	return 0;
}