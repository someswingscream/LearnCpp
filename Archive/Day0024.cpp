// Day0024,对象的初始化和清理
#include <iostream>
#include <string>
#include <vector>

using namespace std;

// 创建Person类作为实例测试
class Person
{
private:
	int person_age;

public:
	// 构造函数可以分为有参构造和无参构造(编译器默认提供无参函数)，也可分为普通构造和拷贝构造，拷贝构造也是有参构造
	Person()
	{
		cout << "调用Person类中无参数构造函数" << '\n';
	}

	// 利用函数重载实现
	Person(int a)
	{
		cout << "调用Person类中有参数构造函数" << '\n';
	}

	// 拷贝函数
	// 拷贝函数实际上就是提供一个复制已经实例化对象内所有数据的方法
	// 调用拷贝函数时将一个已经实例化对象作为参数传入后，通过const和&组合实现仅读获取该参数内数据并赋值给调用参数的对象
	Person(const Person& p)
	{
		cout << "调用Person类中拷贝函数" << '\n';
	}

	// 析构函数
	~Person()
	{
		cout << "调用Person类中析构函数" << '\n';
	}

};

// 作为编译器销毁对象后自动调用对象所属类内析构函数的对照组函数
void ExampleFunc()
{
	Person p4;
}

int main()
{
	// ========== 构造函数和析构函数 ==========
	{
		cout << "构造函数和析构函数测试:" << '\n';

		// c++中对象的初始化和清理都是重要的安全问题
		// 例如使用未初始化的对象或者使用完对象后不进行清理
		// 故C++采取构造函数、析构函数解决上述问题，完成对象的初始化和清理
		// 若不主动提供构造函数和析构函数，编译器会通过空实现的方法提供这两个函数并调用

		// 构造函数:类名(){}
		// 无需返回值和void，函数名称可以与类同名，可以定义参数(可以重载)，程序调用对象时会自动调用构造函数
			// 构造函数的调用，类进行实例化时就会自动调用构造函数
			// 注意事项，想调用默认构造函数或无参数构造函数时，不能以 类名称 实例化对象名称(); 的形式调用，会被认为是函数声明
		Person p1();   // 从左往右结构可视为返回值类型 函数名(); ， 会被编译器当作函数声明而不执行原本想要的操作
		Person p2;     // 调用无参函数
		Person p3(p2); // 调用拷贝函数

		// 析构函数：~类名(){}
		// 无需返回值和void，函数名称可以与类同名，析构函数不能定义参数(也不能重载)，程序会在对象销毁前自动调用析构函数
		// 例如此练习中在此{}后主函数中实例化的对象被销毁，会执行析构函数
		// 对照实验，通过在函数内实例化对象，该对象创建在栈区，函数调用结束后会自动调用析构函数
		ExampleFunc();

		cout << "测试结束" << '\n' << '\n';
	}

	// ========== 显示法调用构造函数 ==========
	{
		cout << '\n' << "显示法调用构造函数测试" << '\n';

		// 无法调用无参构造函数 Person p5 = Person;
		Person p5 = Person(10); // 调用有参函数
		Person p6 = Person(p5); // 调用拷贝函数

		// 类如82行出现的Person(10)就是new语法接触到的匿名对象，它会在当行执行结束后被系统立即回收
		cout << "我在匿名对象之前" << '\n';
		Person(10);
		cout << "我在匿名对象之后" << '\n';

		// 但不要利用拷贝构造函数初始化匿名对象，编译器认为 Person (p7) === Person p7

		// 隐式转化法
		// 很显然此方法使用逻辑和形式都类似于赋值，注意不要混淆
		Person p7 = 10; // 等价于 Person p7 = Person(10)
		Person p8 = p7; // 等价于 Person p8 = Person(p7)

		cout << "测试结束" << '\n' << '\n';
	}
	return 0;
}
