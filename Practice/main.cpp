// Day0013,指针定义,指针与数组实现原理，指针与函数值传递
#include <iostream>
#include <string>
#include <cstdlib>

using namespace std;

void bad(int* p)
{
	p = nullptr;
}

void swapped(int* p1, int* p2)
{
	cout << "交换前：形参指针存的地址: ";
	cout << "p1: " << p1 << "  p2: " << p2 << '\n';

	cout << "交换前：地址指向的内容: ";
	cout << "*p1: " << *p1 << "  *p2: " << *p2 << '\n';

	int p3 = *p1;      // 修正：int 不是 int*
	*p1 = *p2;
	*p2 = p3;

	cout << "交换后：地址指向的内容: ";
	cout << "*p1: " << *p1 << "  *p2: " << *p2 << '\n';

	// 实验：把形参指针置空，验证不影响实参
	p1 = nullptr;
	p2 = nullptr;

	cout << "置空后：形参存的地址: ";
	cout << "p1: " << p1 << "  p2: " << p2 << '\n';
}

int main()
{
// ========== 指针基础 ==========
	// 指针(point):创建实体时根据数据类型分配内存,内存编号即地址,可以通过地址访问内存中的数据,而指针指向数据地址
	{
		int a = 1000;
		// 为数据创建指针:目标数据类型* 指针变量名;
		int* p1;
		// 让指针记录目标变量的地址:指针变量名 = &目标变量名;
		p1 = &a;
		// 打印指针地址
		cout << "变量a的地址为:" << &a << '\n';
		cout << "指针p1内容为:" << p1 << '\n';
		// 使用指针(解引用)可以直接访问或修改地址所存储的数据:*指针变量名
		cout << "p1指针地址所指向的内存,其中数据为:" << *p1 << '\n';
		*p1 = 100;
		cout << "使用*p1修改指针内存中数据为100后,a的值为: " << a << '\n';
	}

// ========== 指针自身的大小 ==========
	// 指针作为一种数据类型,其所占的内存大小为8字节(64位操作系统中),与指针所记录的数据类型无关
	{
		string str1 = "string";
		string* p2 = &str1;
		cout << "记录整型数据的指针p1所占内存大小为:" << sizeof(int*) << "字节" << '\n';
		cout << "记录字符串类型的指针p2所占内存大小为:" << sizeof(p2) << "字节" << '\n';

		// 创建空指针,指向内存编号为0的空间,表示"不指向任何有效内存",无法解引用
		int* p3 = nullptr;
		// 野指针:指向未知地址的指针,会导致未知的随机内存被访问或被修改,必须避免；
		// 对策：定义指针时立即初始化，不确定指向哪就初始化为 nullptr

		// 指针常量、常量指针、const既修饰指针又修饰常量：
		// 指针常量：const修饰"指针"本身（int* const p），指针的指向不可更改，但所指向的数据值可以更改
		// 常量指针：const修饰"所指数据"（const int* p），指针的指向可以更改，但不能通过指针修改数据
		// const既修饰指针又修饰数据（const int* const p）：指向和数据都不可更改
	}

// ========== 数组的实现原理 ==========
	// 数组中的数据存储在连续的、等大的内存中，数组依靠指针实现，访问公式为：首地址 + 下标i × 该数据类型内存大小 = 当前元素地址
	// 数组名在大多数语法场合会直接退化为指针，代表该数组的首地址而非整个数组
	// 不退化的情况如：sizeof(arr)得到整个数组的大小；&arr得到"指向整个数组的指针"，数值上等于arr但类型不同
	{
		cout << '\n' << "利用指针遍历数组arr1测试:" << '\n';
		int arr1[] = { 19,42,52,65 };
		// 在定义阶段*没有解引用的作用，仅是类型声明的一部分
		int* p4 = arr1;

		cout << "数组arr1中的数据为：";
		for (int i = 0; i < 4; ++i)
		{
			// ++这类递增递减运算符的本质是"前进/后退一个单位"，而非数值上加减1：
			// 对数字而言单位一是1，对指针而言单位一是一个元素
			// 此处 *(p4 + i) 即"下i个数组元素"，底层是 p4当前地址 + i × sizeof(int)
			// 故定义指针时必须声明指针的数据类型，且要与目标对象的数据类型保持一致
			cout << *(p4 + i) << ' ';
			// 此处用 (p4 + i) 而不写成 ++p4，是因为 ++p4 会永久移动指针，
			// 养成"领域内产生的影响不遗留到领域外"的习惯
		}
		cout << '\n' << "测试结束" << '\n';
	}

// ========== 指针与函数值传递 ==========
	// 函数值传递通过拷贝完成：程序调用函数时为该函数分配一个栈帧，栈帧负责存储形参+局部变量
	// 局部变量和形参（形参是指针类型也不例外）都分配独立的内存空间，故实参和形参是互不干涉的不同个体
	// 传参时把实参的值拷贝一份给形参，函数体内访问、修改的都是这份拷贝，函数结束时销毁栈帧及其中的一切
	// 传入指针后能修改函数外数值，是因为地址具有唯一性：指针作为实参传入后也会拷贝出一个独立的形参指针，
	// 但两把钥匙开的是同一把锁，通过它仍能访问到函数外的本体
	{
		cout << "指针作为实参传入函数内拷贝测试：" << '\n';
		int value = 5;
		int* pValue = &value;

		bad(pValue);

		cout << '\n' << "在bad函数内将形参p置空后，实参指针pValue为：" << pValue << '\n';
		cout << "测试结束" << '\n' << '\n';
	}

	// 值得注意：函数内的局部变量对函数外的同名变量具有遮蔽效应（作用域屏蔽），
	// 但重定义是另一回事——同一作用域内同名声明会直接编译报错

// ========== swap 实验：地址拷贝与本体修改 ==========
	{
		int num1 = 10;
		int num2 = 12;

		int* pNum1 = &num1;
		int* pNum2 = &num2;

		swapped(pNum1, pNum2);

		cout << "返回后：实参指针存的地址: ";
		cout << "pNum1: " << pNum1 << "  pNum2: " << pNum2 << '\n';

		cout << "返回后：实参指向的内容: ";
		cout << "*pNum1: " << *pNum1 << "  *pNum2: " << *pNum2 << '\n';
	}

	system("pause");

	return 0;
}